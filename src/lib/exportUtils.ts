import { getComponentPins } from './catalog.ts';
import type { CircuitComponent, CustomChipDefinition, Wire } from './types.ts';

const STORAGE_KEY = 'philab_saved_circuit_v1';

export interface SavedCircuitState {
  components: CircuitComponent[];
  wires: Wire[];
  customChips: CustomChipDefinition[];
}

export function saveCircuitToLocalStorage(state: SavedCircuitState): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
  } catch {
    // ignore quota errors
  }
}

export function loadCircuitFromLocalStorage(): SavedCircuitState | null {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return null;
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed?.components) && Array.isArray(parsed?.wires)) {
      return {
        components: parsed.components,
        wires: parsed.wires,
        customChips: Array.isArray(parsed.customChips) ? parsed.customChips : [],
      };
    }
    return null;
  } catch {
    return null;
  }
}

export function encodeCircuitToHash(state: SavedCircuitState): string {
  const json = JSON.stringify(state);
  const bytes = new TextEncoder().encode(json);
  let bin = '';
  for (let i = 0; i < bytes.length; i++) {
    bin += String.fromCharCode(bytes[i]);
  }
  return '#c=' + btoa(bin);
}

export function decodeCircuitFromHash(hash: string): SavedCircuitState | null {
  if (!hash || !hash.startsWith('#c=')) return null;
  try {
    const b64 = hash.slice(3);
    const bin = atob(b64);
    const bytes = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) {
      bytes[i] = bin.charCodeAt(i);
    }
    const json = new TextDecoder().decode(bytes);
    const parsed = JSON.parse(json);
    if (Array.isArray(parsed?.components) && Array.isArray(parsed?.wires)) {
      return {
        components: parsed.components,
        wires: parsed.wires,
        customChips: Array.isArray(parsed.customChips) ? parsed.customChips : [],
      };
    }
    return null;
  } catch {
    return null;
  }
}

export function generateSpiceNetlist(
  components: CircuitComponent[],
  wires: Wire[],
  customChips: CustomChipDefinition[]
): string {
  // Build Union-Find for SPICE net names
  const pinKeys: string[] = [];
  const keyToIdx = new Map<string, number>();
  const reg = (k: string) => {
    let idx = keyToIdx.get(k);
    if (idx === undefined) {
      idx = pinKeys.length;
      pinKeys.push(k);
      keyToIdx.set(k, idx);
    }
    return idx;
  };

  for (const c of components) {
    for (const p of getComponentPins(c, customChips)) {
      reg(`${c.id}:${p.id}`);
    }
  }

  const parent = pinKeys.map((_, i) => i);
  const find = (i: number): number => {
    while (parent[i] !== i) {
      parent[i] = parent[parent[i]];
      i = parent[i];
    }
    return i;
  };
  const union = (a: number, b: number) => {
    const ra = find(a);
    const rb = find(b);
    if (ra !== rb) parent[rb] = ra;
  };

  for (const w of wires) {
    const i1 = keyToIdx.get(`${w.fromCompId}:${w.fromPinId}`);
    const i2 = keyToIdx.get(`${w.toCompId}:${w.toPinId}`);
    if (i1 !== undefined && i2 !== undefined) union(i1, i2);
  }

  const gndRoots = new Set<number>();
  for (const c of components) {
    if (c.type === 'GND' || c.type === 'ARDUINO' || c.type === 'IC555') {
      const idx = keyToIdx.get(`${c.id}:GND`);
      if (idx !== undefined) gndRoots.add(find(idx));
    }
  }

  const rootToNet = new Map<number, string>();
  let netCounter = 1;
  const getNet = (compId: string, pinId: string): string => {
    const idx = keyToIdx.get(`${compId}:${pinId}`);
    if (idx === undefined) return '0';
    const r = find(idx);
    if (gndRoots.has(r)) return '0';
    if (!rootToNet.has(r)) {
      rootToNet.set(r, `N${String(netCounter++).padStart(3, '0')}`);
    }
    return rootToNet.get(r)!;
  };

  const lines: string[] = [
    '* Generated by CircuitFab — Circuit & FPGA Studio',
    '* Compatible with LTSpice / ngspice',
    '',
  ];

  for (const c of components) {
    if (c.type === 'GND') continue;
    if (c.type === 'R') {
      lines.push(`R_${c.label} ${getNet(c.id, 'A')} ${getNet(c.id, 'B')} ${c.value}`);
    } else if (c.type === 'C') {
      lines.push(`C_${c.label} ${getNet(c.id, 'A')} ${getNet(c.id, 'B')} ${c.value}`);
    } else if (c.type === 'L') {
      lines.push(`L_${c.label} ${getNet(c.id, 'A')} ${getNet(c.id, 'B')} ${c.value}`);
    } else if (c.type === 'VDC') {
      lines.push(`V_${c.label} ${getNet(c.id, 'POS')} ${getNet(c.id, 'NEG')} DC ${c.value}`);
    } else if (c.type === 'VAC') {
      lines.push(`V_${c.label} ${getNet(c.id, 'POS')} ${getNet(c.id, 'NEG')} SIN(0 ${c.value} ${c.param2 ?? 4})`);
    } else if (c.type === 'DIODE' || c.type === 'LED') {
      lines.push(`D_${c.label} ${getNet(c.id, 'A')} ${getNet(c.id, 'K')} ${c.type === 'LED' ? 'DLED' : 'D1N4148'}`);
    } else if (c.type === 'NPN' || c.type === 'PNP') {
      lines.push(`Q_${c.label} ${getNet(c.id, 'C')} ${getNet(c.id, 'B')} ${getNet(c.id, 'E')} ${c.type === 'NPN' ? 'Q2N3904' : 'Q2N3906'}`);
    } else if (c.type === 'NMOS') {
      lines.push(`M_${c.label} ${getNet(c.id, 'D')} ${getNet(c.id, 'G')} ${getNet(c.id, 'S')} ${getNet(c.id, 'S')} NMOS_2N7000`);
    } else {
      const pins = getComponentPins(c, customChips).map((p) => getNet(c.id, p.id)).join(' ');
      lines.push(`X_${c.label} ${pins} ${c.type}`);
    }
  }

  lines.push('');
  lines.push('.model D1N4148 D(Is=2.52e-9 Rs=0.568 N=1.752)');
  lines.push('.model DLED D(Is=1e-12 Rs=12 N=3.2)');
  lines.push('.model Q2N3904 NPN(Bf=150 Is=1e-13)');
  lines.push('.model Q2N3906 PNP(Bf=150 Is=1e-13)');
  lines.push('.model NMOS_2N7000 NMOS(Vto=1.5 Kp=0.04)');
  lines.push('.tran 0.1m 200m');
  lines.push('.end');
  return lines.join('\n');
}

export function downloadTextFile(filename: string, content: string, mime = 'text/plain'): void {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

export function exportSvgSchematic(svgEl: SVGSVGElement, filename = 'circuit.svg'): void {
  const serializer = new XMLSerializer();
  const src = serializer.serializeToString(svgEl);
  downloadTextFile(filename, src, 'image/svg+xml');
}

export function exportPngSchematic(svgEl: SVGSVGElement, filename = 'circuit.png'): void {
  const serializer = new XMLSerializer();
  const src = serializer.serializeToString(svgEl);
  const svgBlob = new Blob([src], { type: 'image/svg+xml;charset=utf-8' });
  const url = URL.createObjectURL(svgBlob);
  const img = new Image();
  img.onload = () => {
    const canvas = document.createElement('canvas');
    canvas.width = svgEl.clientWidth || 1200;
    canvas.height = svgEl.clientHeight || 800;
    const ctx = canvas.getContext('2d');
    if (ctx) {
      ctx.fillStyle = '#F8F9FA';
      ctx.fillRect(0, 0, canvas.width, canvas.height);
      ctx.drawImage(img, 0, 0);
      canvas.toBlob((pngBlob) => {
        if (pngBlob) {
          const pUrl = URL.createObjectURL(pngBlob);
          const a = document.createElement('a');
          a.href = pUrl;
          a.download = filename;
          a.click();
          URL.revokeObjectURL(pUrl);
        }
      }, 'image/png');
    }
    URL.revokeObjectURL(url);
  };
  img.src = url;
}
